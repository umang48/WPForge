document.addEventListener('DOMContentLoaded', () => {
    const filterButtons = document.querySelectorAll('.filter-btn');
    const projectGrid = document.getElementById('project-grid');

    if (!filterButtons.length || !projectGrid) return;

    filterButtons.forEach(button => {
        button.addEventListener('click', function(e) {
            e.preventDefault();
            
            const termSlug = this.getAttribute('data-filter');
            
            // UI Update: Manage active state classes
            filterButtons.forEach(btn => {
                btn.style.background = 'transparent';
                btn.style.color = '#0073aa';
            });
            this.style.background = '#0073aa';
            this.style.color = '#fff';

            // Visual feedback while loading
            projectGrid.style.opacity = '0.5';

            // Prepare form data for WordPress AJAX
            const formData = new FormData();
            formData.append('action', 'wpforge_filter_projects');
            formData.append('term', termSlug);
            formData.append('nonce', wpforgeData.nonce); // Provided by wp_localize_script

            // Fetch request to admin-ajax.php
            fetch(wpforgeData.ajax_url, {
                method: 'POST',
                body: formData
            })
            .then(response => {
                if (!response.ok) {
                    throw new Error('Network response was not ok');
                }
                return response.json();
            })
            .then(data => {
                if (data.success) {
                    // Inject the new HTML payload generated by our PHP output buffer
                    projectGrid.innerHTML = data.data;
                } else {
                    console.error('AJAX Error:', data);
                    projectGrid.innerHTML = `<p>${wpforgeData.error_msg}</p>`;
                }
            })
            .catch(error => {
                console.error('Fetch Error:', error);
                projectGrid.innerHTML = `<p>${wpforgeData.error_msg}</p>`;
            })
            .finally(() => {
                // Restore opacity
                projectGrid.style.opacity = '1';
            });
        });
    });
});